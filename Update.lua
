local dictFile = os.getenv("EXTERNAL_STORAGE") .. "/openrouter_typer_dict.dat"
local changeTable = {}
-- NEW: lowercase index — chahe dictionary mein 100 words ho ya 100,000,
-- lookup hamesha O(1) (instant) rahega, kyunke har baar poori dictionary
-- text mein "search" nahi hoti, sirf ek table lookup hoti hai.
local changeTableLower = {}

-- NEW: har dafa changeTable badalne ke baad yeh call karo taake
-- changeTableLower hamesha sync rahe.
function rebuildDictionaryIndex()
    changeTableLower = {}
    for wrong, correct in pairs(changeTable) do
        if type(wrong) == "string" and type(correct) == "string" then
            changeTableLower[wrong:lower()] = correct
        end
    end
end

function loadDictionary()
    local f = io.open(dictFile, "r")
    if f then
        local content = f:read("*all")
        f:close()
        if content and content ~= "" then
            local ok, result = pcall(cjson.decode, content)
            if ok and type(result) == "table" then
                changeTable = result
            else
                changeTable = {}
            end
        end
    end
    rebuildDictionaryIndex()
end

function saveDictionary()
    local f = io.open(dictFile, "w")
    if f then
        f:write(cjson.encode(changeTable))
        f:close()
    end
    rebuildDictionaryIndex()
end

function addToDictionary(wrongWord, correctWord)
    if wrongWord and correctWord and wrongWord ~= "" and correctWord ~= "" then
        changeTable[wrongWord] = correctWord
        saveDictionary()
        return true
    end
    return false
end

-- ==================== NEW: Fast, single-pass dictionary correction ====================
-- Purana tareeqa har dictionary entry ke liye poora text scan karta tha (30,000
-- entries ke sath bohot slow/hang ho jata). Yeh naya tareeqa text ko sirf EK
-- baar words mein todta hai aur har word ko table mein O(1) dhoondta hai —
-- dictionary chahe 10 words ki ho ya 30,000 ki, speed same rahegi.
function applyDictionaryCorrections(text)
    if not text or text == "" or next(changeTableLower) == nil then
        return text
    end

    local result = {}
    local pos = 1
    local len = #text
    while pos <= len do
        local ws, we = text:find("^%s+", pos)
        if ws then
            table.insert(result, text:sub(ws, we))
            pos = we + 1
        else
            local ns, ne = text:find("%S+", pos)
            if not ns then break end
            local word = text:sub(ns, ne)
            -- word ke aakhir se punctuation (., !, ?, ,) alag karo taake lookup match ho
            local core, trail = word:match("^(.-)([%.%!%?%,;:]*)$")
            if not core or core == "" then
                core = word
                trail = ""
            end
            local replacement = changeTableLower[core:lower()]
            if replacement then
                table.insert(result, replacement .. trail)
            else
                table.insert(result, word)
            end
            pos = ne + 1
        end
    end
    return table.concat(result)
end

