-- Byte-level heuristic: agar text mein pehle se emoji character mojood hai
function textContainsEmoji(text)
    if not text or text == "" then return false end
    for i = 1, #text do
        local b = text:byte(i)
        if b and b >= 240 then -- 0xF0+ : zyada tar modern emoji (4-byte UTF-8)
            return true
        end
    end
    -- Symbol emoji jo 3-byte UTF-8 hain (☀ ❤ ✅ ❌ ⚠ ✨ ✋ waghaira, lead byte 0xE2)
    if text:find("\226\152") or text:find("\226\156") or text:find("\226\157")
       or text:find("\226\154") or text:find("\226\159") or text:find("\226\156\168") then
        return true
    end
    return false
end

-- Sentence ke alfaaz check karke sahi emoji dhoondta hai; na mile to
-- punctuation ke hisab se ek acha default deta hai (kabhi khaali nahi jata).
function pickEmojiForSentence(sentence)
    if sentence and sentence ~= "" then
        for word in sentence:gmatch("%a+") do
            local match = KEYWORD_EMOJI[word:lower()]
            if match then
                return match
            end
        end
    end
    if sentence:find("!%s*$") then return "😃" end
    if sentence:find("%?%s*$") then return "🤔" end
    return "🙂"
end

function splitIntoSentences(text)
    local sentences = {}
    local pos = 1
    local len = #text
    while pos <= len do
        local s, e = text:find("[^.!?]*[.!?]+", pos)
        if not s then break end
        table.insert(sentences, text:sub(s, e))
        pos = e + 1
    end
    -- Baaki bacha hua text jisme punctuation na ho (aakhri adhoora jumla)
    local consumed = 0
    for _, s in ipairs(sentences) do
        consumed = consumed + #s
    end
    local remainder = text:sub(pos)
    if remainder and remainder:match("%S") then
        table.insert(sentences, remainder)
    end
    -- Trim spaces
    for i, s in ipairs(sentences) do
        sentences[i] = s:match("^%s*(.-)%s*$")
    end
    return sentences
end

function applyAfterSentenceFormat(text, styleIndex, emojiEnabled)
    if not text or text == "" then return text end

    local sentences = splitIntoSentences(text)
    if #sentences == 0 then return text end

    -- GUARANTEED emoji: agar emoji ON hai aur kisi sentence mein pehle se
    -- emoji nahi hai, to yahan khud laga do — AI ke bharose nahi rehna.
    if emojiEnabled then
        for i, s in ipairs(sentences) do
            if s ~= "" and not textContainsEmoji(s) then
                sentences[i] = s .. " " .. pickEmojiForSentence(s)
            end
        end
    end

    local separator = " "
    if styleIndex == 3 or styleIndex == 4 then
        separator = "\n"
    end

    return table.concat(sentences, separator)
end

