function testOpenRouterAPI(apiKey, model, callback)
    local url = "https://openrouter.ai/api/v1/auth/key"
    local headers = {
        ["Authorization"] = "Bearer " .. apiKey
    }
    
    Http.get(url, headers, function(status, data)
        if status == 200 then
            callback(true, "API key is valid!")
        elseif status == 401 then
            callback(false, "Invalid API key")
        else
            callback(false, "Error: " .. status)
        end
    end)
end

function callOpenRouterAPI(apiKey, model, prompt, callback)
    local url = "https://openrouter.ai/api/v1/chat/completions"
    local headers = {
        ["Content-Type"] = "application/json",
        ["Authorization"] = "Bearer " .. apiKey,
        ["HTTP-Referer"] = "https://github.com/NomanKhan",
        ["X-Title"] = "AI Typer by Noman Khan"
    }
    local payload = {
        model = model,
        messages = {{role = "user", content = prompt}},
        max_tokens = 4096, -- bahut lambi typing ke liye aur badhaya gaya
        temperature = 0.7
    }
    
    Http.post(url, cjson.encode(payload), headers, function(status, data)
        if status == 200 then
            local ok, decoded = pcall(cjson.decode, data)
            if ok and decoded and decoded.choices and decoded.choices[1] then
                local text = decoded.choices[1].message.content
                if text then
                    callback(text, nil)
                else
                    callback(nil, "Invalid response from OpenRouter")
                end
            else
                callback(nil, "Failed to parse OpenRouter response")
            end
        elseif status == 401 then
            callback(nil, "Invalid API key. Please check your OpenRouter API key")
        elseif status == 429 then
            callback(nil, "Rate limit exceeded. Please wait or check your quota")
        else
            callback(nil, "OpenRouter Error: " .. status)
        end
    end)
end

