            Button;
            text = "About " .. APP_NAME;
            textSize = "16sp";
            layout_width = "fill";
            layout_marginBottom = "10dp";
            onClick = function()
                dlg.dismiss()
                showAboutDialog(dlg)
            end;
        };
        {
            Button;
            text = "Exit";
            textSize = "16sp";
            layout_width = "fill";
            onClick = function()
                dlg.dismiss()
            end;
        };
