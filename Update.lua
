-- Byte-level heuristic: agar text mein pehle se emoji character mojood hai
function textContainsEmoji(text)
    if not text or text == "" then return false end
    for i = 1, #text do
        local b = text:byte(i)
        if b and b >= 240 then -- 0xF0+ : zyada tar modern emoji (4-byte UTF-8)
            return true
        end
    end
    -- Symbol emoji jo 3-byte UTF-8 hain (☀ ❤ ✅ ❌ ⚠ ✨ ✋ waghaira, lead byte 0xE2)
    if text:find("\226\152") or text:find("\226\156") or text:find("\226\157")
       or text:find("\226\154") or text:find("\226\159") or text:find("\226\156\168") then
        return true
    end
    return false
end

-- Sentence ke alfaaz check karke sahi emoji dhoondta hai; na mile to
-- punctuation ke hisab se ek acha default deta hai (kabhi khaali nahi jata).
function pickEmojiForSentence(sentence)
    if sentence and sentence ~= "" then
        for word in sentence:gmatch("%a+") do
            local match = KEYWORD_EMOJI[word:lower()]
            if match then
                return match
            end
        end
    end
    if sentence:find("!%s*$") then return "😃" end
    if sentence:find("%?%s*$") then return "🤔" end
    if sentence:find("\216\159%s*$") then return "🤔" end -- ؟ Urdu question mark
    return "🙂"
end

-- FIX: Ab yeh Angrezi (. ! ?) aur Urdu script ke punctuation (۔ ؟) dono ko
-- sentence ka aakhir samajhta hai — pehle sirf Angrezi wale pehchane jaate
-- the, is liye Urdu script mein poora paragraph "ek hi sentence" ban jata
-- tha aur emoji sirf akhir mein lagti thi.
function splitIntoSentences(text)
    local sentences = {}
    local buffer = {}
    local i = 1
    local len = #text

    local function isTerminatorAt(pos)
        local b1 = text:byte(pos)
        if b1 == 46 or b1 == 33 or b1 == 63 then -- . ! ?
            return true, 1
        end
        if pos + 1 <= len then
            local b2 = text:byte(pos + 1)
            if (b1 == 219 and b2 == 148) or (b1 == 216 and b2 == 159) then -- ۔ ؟
                return true, 2
            end
        end
        return false, 0
    end

    while i <= len do
        local isTerm, termLen = isTerminatorAt(i)
        if isTerm then
            table.insert(buffer, text:sub(i, i + termLen - 1))
            i = i + termLen
            -- lagatar aane wale terminators bhi (jaise "?!" ya "۔۔۔") isi sentence mein shamil karo
            local moreTerm, moreLen = isTerminatorAt(i)
            while moreTerm do
                table.insert(buffer, text:sub(i, i + moreLen - 1))
                i = i + moreLen
                moreTerm, moreLen = isTerminatorAt(i)
            end
            table.insert(sentences, table.concat(buffer))
            buffer = {}
        else
            table.insert(buffer, text:sub(i, i))
            i = i + 1
        end
    end

    if #buffer > 0 then
        local remainder = table.concat(buffer)
        if remainder:match("%S") then
            table.insert(sentences, remainder)
        end
    end

    for idx, s in ipairs(sentences) do
        sentences[idx] = s:match("^%s*(.-)%s*$")
    end
    return sentences
end

function applyAfterSentenceFormat(text, styleIndex, emojiEnabled)
    if not text or text == "" then return text end

    local sentences = splitIntoSentences(text)
    if #sentences == 0 then return text end

    -- GUARANTEED emoji: agar emoji ON hai aur kisi sentence mein pehle se
    -- emoji nahi hai, to yahan khud laga do — AI ke bharose nahi rehna.
    if emojiEnabled then
        for i, s in ipairs(sentences) do
            if s ~= "" and not textContainsEmoji(s) then
                sentences[i] = s .. " " .. pickEmojiForSentence(s)
            end
        end
    end

    local separator = " "
    if styleIndex == 3 or styleIndex == 4 then
        separator = "\n"
    end

    return table.concat(sentences, separator)
end

