function startVoiceTyping(langCode)
    local context = service.getApplicationContext()
    local speechRec = SpeechRecognizer.createSpeechRecognizer(context)
    
    local listener = RecognitionListener {
        onResults = function(results)
            local resultsArray = results.getParcelableArrayList(SpeechRecognizer.RESULTS_RECOGNITION)
            if resultsArray and resultsArray.size() > 0 then
                local spokenText = resultsArray.get(0)
                -- NEW: fast, single-pass dictionary correction (30,000+ words ke sath bhi tez)
                spokenText = applyDictionaryCorrections(spokenText)
                spokenText = spokenText:gsub("%s([?,!])", "%1")
                if not spokenText:match("[.?!,.]$") then
                    spokenText = spokenText .. ". "
                end
                
                local activeProvider = getActiveProvider()
                local apiKey = (activeProvider == "Mistral AI") and getMistralApiKey() or getOpenRouterApiKey()
                
                if apiKey and apiKey ~= "" then
                    service.speak("AI processing...")
                    processWithAI(spokenText, function(enhancedText)
                        -- NEW: apply the chosen after-sentence format as a safety net
                        local styleIndex = getAfterSentenceStyleIndex()
                        local formatted = applyAfterSentenceFormat(enhancedText, styleIndex, isEmojiEnabled())
                        service.insertText(editText, formatted)
                        service.speak(formatted)
                    end)
                else
                    service.insertText(editText, spokenText)
                    service.speak(spokenText)
                end
            end
            speechRec.destroy()
        end,
        onError = function(errorCode)
            service.asyncSpeak("I did not understand your message")
            speechRec.destroy()
            return false
        end,
    }
    
    local intent = Intent(RecognizerIntent.ACTION_RECOGNIZE_SPEECH)
    intent.putExtra(RecognizerIntent.EXTRA_LANGUAGE_MODEL, RecognizerIntent.LANGUAGE_MODEL_FREE_FORM)
    intent.putExtra(RecognizerIntent.EXTRA_LANGUAGE, langCode)
    -- NEW: lambi dictation ke liye — thodi si khamoshi (pause) par turant na ruke
    intent.putExtra("android.speech.extra.SPEECH_INPUT_COMPLETE_SILENCE_LENGTH_MILLIS", 3000)
    intent.putExtra("android.speech.extra.SPEECH_INPUT_POSSIBLY_COMPLETE_SILENCE_LENGTH_MILLIS", 3000)
    intent.putExtra("android.speech.extra.SPEECH_INPUT_MINIMUM_LENGTH_MILLIS", 15000)
    speechRec.setRecognitionListener(listener)
    speechRec.startListening(intent)
end

